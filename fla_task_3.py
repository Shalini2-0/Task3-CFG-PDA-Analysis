def palindrome_stack_trace(string):
    if not all(ch in "ab" for ch in string):
        print("REJECTED: Invalid alphabet")
        return

    if string != string[::-1]:
        print("Input:", string)
        print("REJECTED: String is not a palindrome")
        return

    midpoint = len(string) // 2

    left_half = string[:midpoint]
    right_half = string[midpoint:]

    stack = ["Z₀"]

    print("Input string:", string)
    print("Left half:", left_half)
    print("Right half:", right_half)
    print("\nPUSH PHASE")

    for symbol in left_half:
        stack.append(symbol)
        print(f"Read {symbol} -> Push | Stack: {stack}")

    print("\nMATCH AND POP PHASE")

    for symbol in right_half:
        top = stack[-1]

        if top == symbol:
            stack.pop()
            print(f"Read {symbol} -> Match and pop | Stack: {stack}")
        else:
            print("Mismatch found: REJECTED")
            return

    if stack == ["Z₀"]:
        print("\nFinal result: ACCEPTED")
        print("All symbols matched successfully.")

