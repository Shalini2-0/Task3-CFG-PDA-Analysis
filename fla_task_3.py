def draw_parse_tree(expression, tree, title):
    """
    tree format:
    (node_label, [child1, child2, ...])
    """
    G = nx.DiGraph()
    positions = {}
    labels = {}
    counter = [0]

    def build_tree(node, depth=0, x=0):
        node_id = counter[0]
        counter[0] += 1

        if isinstance(node, tuple):
            label, children = node
        else:
            label, children = node, []

        G.add_node(node_id)
        labels[node_id] = label
        positions[node_id] = (x, -depth)

        if children:
            width = len(children)
            child_x_positions = [
                x + (i - (width - 1) / 2) * (2.0 / (depth + 1))
                for i in range(width)
            ]

            for child, child_x in zip(children, child_x_positions):
                child_id = build_tree(child, depth + 1, child_x)
                G.add_edge(node_id, child_id)

        return node_id

    build_tree(tree)

    plt.figure(figsize=(10, 5))
    nx.draw(
        G,
        positions,
        labels=labels,
        with_labels=True,
        node_size=2600,
        node_color="lightblue",
        font_size=10,
        font_weight="bold",
        arrows=False,
        edge_color="gray"
    )

    plt.title(f"Parse Tree: {expression}", fontsize=14, fontweight="bold")
    plt.axis("off")
    plt.tight_layout()
