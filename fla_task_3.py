# Context-Free Grammar:
# S -> (S)S | epsilon

def is_balanced_parentheses(string):
    """
    Check whether parentheses are balanced using a stack.
    Returns True for valid strings and False otherwise.
    """

    stack = []

    for symbol in string:

        if symbol == '(':
            # Push opening parenthesis
            stack.append(symbol)

        elif symbol == ')':
            # Closing parenthesis requires a matching opening one
            if not stack:
                return False

            stack.pop()

        else:
            # Characters other than parentheses are not allowed
            return False

    # Valid only when no unmatched opening parentheses remain
    return len(stack) == 0


